#!/usr/bin/env python3
"""Generate src/Retrace/Engine/Util/FontMetricsData.cs: per-character advance widths (px) for the
fonts and pixel sizes a Windows 10/11 dialog uses at 96 DPI. Only numbers are emitted, never font data.

Sources, in order of preference:
  1. GDI measurements taken on real Windows 11 at 96 DPI: a JSON file
     {"Face|px|weight": {"widths": {"value": [95 ints]}, "ascent": n, "descent": n}} made with GetCharWidth32
     for chars 32..126. Authoritative, and the only source for Segoe UI (not on macOS). Marked "gdi" in the output.
  2. TTFs from /System/Library/Fonts/Supplemental (macOS; override with FONT_DIR): `hdmx` hinted widths when the
     ppem is present, else hmtx scaled. Marked "ttf".

Run (fontTools is only needed for the "ttf" rows):
    python3 tools/gen_font_metrics.py src/Retrace/Engine/Util/FontMetricsData.cs --gdi gdiwidths.json
"""
import json
import math
import os
import sys

from fontTools.ttLib import TTFont

FONT_DIR = os.environ.get("FONT_DIR", "/System/Library/Fonts/Supplemental")
# table key, ttf file, ppems wanted from the ttf when no GDI row exists
FONTS = [
    ("MicrosoftSansSerif", "Microsoft Sans Serif.ttf", [11, 12, 13]),
    ("Tahoma", "Tahoma.ttf", [11, 12, 13]),
    ("TahomaBold", "Tahoma Bold.ttf", [11, 12]),
    ("Arial", "Arial.ttf", [11, 12, 13]),
]
# GDI json key -> (table key, ppem)
GDI_KEYS = {
    "Tahoma|11|400": ("Tahoma", 11),
    "Tahoma|11|700": ("TahomaBold", 11),
    "Segoe UI|11|400": ("SegoeUI", 11),
    "Segoe UI|12|400": ("SegoeUI", 12),
    "Arial|12|400": ("Arial", 12),
    "Microsoft Sans Serif|11|400": ("MicrosoftSansSerif", 11),
}


def ttf_widths(font, ppem):
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    upem = font["head"].unitsPerEm
    hd = font["hdmx"].hdmx.get(ppem) if "hdmx" in font else None
    out = []
    for cp in range(32, 127):
        g = cmap.get(cp)
        if g is None:
            out.append(0)
        elif hd is not None and g in hd:
            out.append(int(hd[g]))
        else:
            out.append(int(round(hmtx[g][0] * ppem / upem)))
    return out


def main(path, gdi_path=None):
    gdi = {}
    if gdi_path:
        for k, v in json.load(open(gdi_path)).items():
            if k in GDI_KEYS:
                gdi[GDI_KEYS[k]] = (v["widths"]["value"], int(v["ascent"]))
    rows = {}  # (key, ppem) -> (widths, ascent, source)
    for (key, ppem), (w, asc) in gdi.items():
        rows[(key, ppem)] = (w, asc, "gdi")
    for key, file, ppems in FONTS:
        f = None
        for ppem in ppems:
            if (key, ppem) in rows:
                continue
            if f is None:
                f = TTFont(os.path.join(FONT_DIR, file))
            upem = f["head"].unitsPerEm
            # GDI ascent: winAscent scaled, rounded up (tolerance for 2049/2048-style values)
            asc = int(math.ceil(f["OS/2"].usWinAscent * ppem / upem - 0.02))
            rows[(key, ppem)] = (ttf_widths(f, ppem), asc, "ttf")

    lines = [
        "// <auto-generated> by tools/gen_font_metrics.py - do not edit by hand. Numbers only, no font data.",
        "// Rows marked gdi were measured with GDI on Windows 11 at 96 DPI; rows marked ttf come from macOS TTF hdmx/hmtx.",
        "namespace Retrace.Engine.Util;",
        "",
        "internal static class FontMetricsData",
        "{",
        "    /// <summary>(font key, ppem) -> advance widths of ASCII 32..126, ascent px, average width px.</summary>",
        "    public static readonly Dictionary<(string Font, int Ppem), (int[] Widths, int Ascent, int Avg)> Tables = new()",
        "    {",
    ]
    for (key, ppem), (w, asc, src) in sorted(rows.items()):
        nz = [x for x in w[1:] if x]
        avg = int(round(sum(nz) / len(nz)))
        lines.append(f'        [("{key}", {ppem})] = (new[] {{ {", ".join(map(str, w))} }}, {asc}, {avg}), // {src}')
    lines += ["    };", "}", ""]
    with open(path, "w") as fh:
        fh.write("\n".join(lines))


if __name__ == "__main__":
    argv = sys.argv[1:]
    gdi = None
    if "--gdi" in argv:
        i = argv.index("--gdi")
        gdi = argv[i + 1]
        del argv[i:i + 2]
    main(argv[0] if argv else "src/Retrace/Engine/Util/FontMetricsData.cs", gdi)
