// Markdown pages: README, ribbon tabs, commands with flows, dialogs, projects.
using System.Text;
using Retrace.Engine.Util;

namespace Retrace.Engine.Emit;

public sealed class DocsWriter(ModelIndex ix, OutputSink sink)
{
    private EngineModel M => ix.Model;

    public void WriteAll()
    {
        WriteReadme();
        WriteProjects();
        WriteRibbonIndex();
        foreach (var tab in ix.AllTabs) WriteTab(tab);
        WriteCommandIndex();
        foreach (var g in M.Commands.GroupBy(c => c.Project)) WriteCommandPage(g.Key, g.ToList());
        WriteUiIndex();
        foreach (var f in M.Forms) WriteForm(f);
    }

    // ------------------------------------------------------------ README

    private void WriteReadme()
    {
        const string doc = "README.md";
        var sb = new StringBuilder();
        sb.Append($"""
            # AutoCAD UI map

            Generated by Retrace from `{M.InputRoot}` on {M.Generated:yyyy-MM-dd HH:mm}.
            This folder describes the AutoCAD user interface defined by the scanned customization
            files and source code: ribbon tabs, command entry points, the UI each command walks
            through, and the dialogs it opens. Every element points back to the file and line
            that defines it.

            ## How to read this

            - [guide/index.md](guide/index.md): the user guide. Its pages are for you to edit: write outside the
              `<!-- engine:begin ... -->` blocks and the engine keeps your text on every run.
            - [reference/ribbon/index.md](reference/ribbon/index.md): ribbon tabs from `.cuix` files and from code.
            - [reference/commands/index.md](reference/commands/index.md): every command entry point and its UI flow.
            - [reference/dialogs/index.md](reference/dialogs/index.md): dialogs, windows and palettes, with wireframes.
            - [reference/projects.md](reference/projects.md): the scanned projects and files.
            - [test-plans/index.md](test-plans/index.md): manual test scripts written from the source.
            {RecordingsLine()}- [data/sourcemap.json](data/sourcemap.json): one entry per UI element (ribbon tab, panel and button,
              command, dialog) with its source location, wireframe, reference page, how to reach it in
              AutoCAD, and a capture hint for taking a real screenshot.

            The `reference` folder is rewritten on every run: do not edit it. Wireframes in `reference/images/` are drawn
            from the source, not captured from AutoCAD. Each SVG element carries a `data-source="file:line"` attribute.

            ## Counts

            """);
        sb.Append(Md.Table(new[] { "What", "Count" }, new[]
        {
            new[] { "Projects", M.Projects.Count.ToString() },
            new[] { "Source files read", M.Files.Count.ToString() },
            new[] { "CUIX files", M.Cuix.Count.ToString() },
            new[] { "Ribbon tabs from CUIX", M.Cuix.Sum(c => c.Tabs.Count).ToString() },
            new[] { "Ribbon tabs from code", M.CodeTabs.Count.ToString() },
            new[] { "Ribbon buttons", ix.AllTabs.Sum(t => Linker.Walk(t).Count()).ToString() },
            new[] { "Command entry points", M.Commands.Count.ToString() },
            new[] { "Dialogs / windows / palettes", M.Forms.Count.ToString() },
        }));
        if (M.Skipped.Count > 0)
        {
            sb.Append("\n## Skipped files\n\nThese files were not opened:\n\n");
            foreach (var s in M.Skipped) sb.Append($"- `{s}`\n");
        }
        if (M.Warnings.Count > 0)
        {
            sb.Append("\n## Warnings\n\n");
            foreach (var w in M.Warnings) sb.Append($"- {w}\n");
        }
        sink.Write(doc, sb.ToString());
    }

    /// <summary>The README bullet for the recordings pages, when this run wrote them (ends with a newline).</summary>
    private string RecordingsLine() =>
        File.Exists(Path.Combine(ix.Options.Output, DocsLayout.Recordings, "index.md"))
            ? "- [recordings/index.md](recordings/index.md): the recorded tests: most used buttons, ribbon coverage, one page per test.\n"
            : "";

    private void WriteProjects()
    {
        var sb = new StringBuilder("# Projects\n\n");
        sb.Append(Md.Table(new[] { "Project", "Folder", "Language", "Files", "Commands", "Dialogs", "Ribbon tabs" },
            M.Projects.Select(p => new[]
            {
                p.Name, p.Dir.Length == 0 ? "." : p.Dir, p.Lang.ToString(), p.Files.Count.ToString(),
                M.Commands.Count(c => c.Project == p.Name).ToString(),
                M.Forms.Count(f => f.Project == p.Name).ToString(),
                M.CodeTabs.Count(t => t.Container == p.Name).ToString(),
            })));
        sink.Write(DocsLayout.RefProjects, sb.ToString());
    }

    // ------------------------------------------------------------ ribbon

    private void WriteRibbonIndex()
    {
        const string doc = DocsLayout.RefRibbon + "/index.md";
        var sb = new StringBuilder("# Ribbon tabs\n\n");
        foreach (var c in M.Cuix)
        {
            sb.Append($"## {c.File} (menu group {c.MenuGroup})\n\n");
            if (c.Workspaces.Count > 0) sb.Append($"Workspaces: {string.Join(", ", c.Workspaces)}\n\n");
            if (c.PartialMenus.Count > 0) sb.Append($"Partial menus referenced (read too when the setting loadedCustomization is on): {string.Join(", ", c.PartialMenus)}\n\n");
            sb.Append(TabTable(doc, c.Tabs));
        }
        if (M.CodeTabs.Count > 0)
        {
            sb.Append("## Built in code\n\n");
            sb.Append(TabTable(doc, M.CodeTabs));
        }
        sink.Write(doc, sb.ToString());
    }

    private string TabTable(string doc, IEnumerable<RibbonTab> tabs) =>
        Md.Table(new[] { "Tab", "Id", "Panels", "Buttons", "Shown in", "Source" },
            tabs.Select(t => new[]
            {
                $"[{Md.Cell(t.Title)}]({Md.Rel(doc, ix.TabDoc[t])})", Md.Code(t.Id), t.Panels.Count.ToString(),
                Linker.Walk(t).Count().ToString(),
                t.ContextualRule != null ? $"contextual: {t.ContextualRule}" : string.Join(", ", t.Workspaces),
                Md.Code(t.Source?.ToString()),
            })) + "\n";

    private void WriteTab(RibbonTab tab)
    {
        var doc = ix.TabDoc[tab];
        var sb = new StringBuilder();
        sb.Append($"# Ribbon tab: {tab.Title}\n\n");
        sb.Append($"![{tab.Title} {ix.TabPictureName(tab)}]({Md.Rel(doc, ix.TabAsset[tab])})\n\n");
        sb.Append(Md.Table(new[] { "Field", "Value" }, new List<string?[]>
        {
            new[] { "Id", Md.Code(tab.Id) },
            new[] { "Origin", tab.Origin == RibbonOrigin.Cuix ? $"CUIX `{tab.Container}`" : $"code, project {tab.Container}" },
            new[] { "Source", Md.Code(tab.Source?.ToString()) },
            new[] { "Display name", tab.DisplayName },
            new[] { "Key tip", tab.KeyTip },
            new[] { "Workspaces", string.Join(", ", tab.Workspaces) },
            new[] { "Contextual rule", tab.ContextualRule },
            new[] { "Source map id", Md.Code(ModelIndex.TabId(tab)) },
        }.Where(r => !string.IsNullOrEmpty(r[1]))));
        sb.Append("\n**How to reach it:** ").Append(string.Join(" → ", ix.ReachTab(tab))).Append("\n\n");

        foreach (var p in tab.Panels)
        {
            sb.Append($"## Panel: {p.Title}\n\n");
            var meta = new List<string> { $"id {Md.Code(p.Id)}" };
            if (p.Source != null) meta.Add($"source {Md.Code(p.Source.ToString())}");
            if (p.DialogLauncherCommand != null) meta.Add($"dialog launcher runs {Md.Code(p.DialogLauncherCommand)}");
            sb.Append(string.Join(", ", meta)).Append("\n\n");
            var rows = new List<string?[]>();
            int rowNo = 0;
            foreach (var r in p.Rows)
            {
                rowNo++;
                foreach (var (panel, item, parent, slide) in WalkRow(p, r))
                {
                    if (item.Kind == RibbonItemKind.RowPanel) continue; // container; its items follow

                    var entries = ix.EntriesFor(item).ToList();
                    rows.Add(new[]
                    {
                        $"{rowNo}{(slide ? " (slide-out)" : "")}",
                        (parent != null ? "↳ " : "") + Md.Cell(ModelIndex.Label(item)),
                        $"{item.Kind}{(item.Kind is RibbonItemKind.Separator ? "" : ", " + item.Size)}",
                        Md.Code(item.Command),
                        item.HandlerMethod != null ? Md.Code(item.HandlerMethod) : Md.Code(Trunc(item.Macro, 60)),
                        string.Join(", ", entries.Select(e => $"[{Md.Cell(e.Name)}]({ix.CommandLink(doc, e)})")),
                        Md.Cell(item.Tooltip),
                        Md.Code(item.Source?.ToString()),
                    });
                }
            }
            sb.Append(Md.Table(new[] { "Row", "Button", "Kind", "Command", "Macro / handler", "Code entry point", "Tooltip", "Source" }, rows));
            sb.Append('\n');
        }
        sink.Write(doc, sb.ToString());
    }

    private static IEnumerable<(RibbonPanel, RibbonItem, RibbonItem?, bool)> WalkRow(RibbonPanel p, RibbonRow r)
    {
        var tmp = new RibbonTab { Id = "_", Title = "_" };
        var tp = new RibbonPanel { Id = p.Id, Title = p.Title };
        tp.Rows.Add(r);
        tmp.Panels.Add(tp);
        return Linker.Walk(tmp).Select(w => (p, w.item, w.parent, w.slideout));
    }

    // ------------------------------------------------------------ commands

    private void WriteCommandIndex()
    {
        const string doc = DocsLayout.RefCommands + "/index.md";
        var sb = new StringBuilder("# Command entry points\n\n");
        sb.Append("Every way into the scanned code from AutoCAD: registered commands (.NET `CommandMethod`, ObjectARX\n");
        sb.Append("`addCommand` / `ACED_ARXCOMMAND_ENTRY`), LISP functions, and methods that ribbon buttons call directly.\n\n");
        sb.Append(Md.Table(new[] { "Command", "Kind", "Lang", "Project", "Method", "Ribbon", "Opens", "Source" },
            M.Commands.OrderBy(c => c.Project).ThenBy(c => c.Name).Select(c => new[]
            {
                $"[{Md.Cell(c.Name)}]({ix.CommandLink(doc, c)})", c.Kind.ToString(), c.Lang.ToString(), c.Project,
                Md.Code(c.Method),
                string.Join("; ", ix.RibbonFor(c)
                    .Take(3).Select(h => $"{h.Tab.Title} › {ModelIndex.Label(h.Item)}")),
                string.Join(", ", Opens(c).Select(f => $"[{Md.Cell(f.Title)}]({Md.Rel(doc, ix.FormDoc[f])})")),
                Md.Code(c.Source.ToString()),
            })));
        sink.Write(doc, sb.ToString());
    }

    private IEnumerable<UiForm> Opens(CommandEntry c) =>
        c.Flow.Where(s => s.UiFormId != null).Select(s => ix.FormsById[s.UiFormId!]).Distinct();

    private void WriteCommandPage(string project, List<CommandEntry> cmds)
    {
        var doc = ix.CommandDoc[project];
        var sb = new StringBuilder($"# Commands in {project}\n\n");
        foreach (var c in cmds.OrderBy(c => c.Name, StringComparer.OrdinalIgnoreCase))
        {
            sb.Append($"<a id=\"{ix.CommandAnchor[c]}\"></a>\n\n## {c.Name}\n\n");
            sb.Append(Md.Table(new[] { "Field", "Value" }, new List<string?[]>
            {
                new[] { "Kind", c.Kind.ToString() },
                new[] { "Method", Md.Code(c.Method) },
                new[] { "Source", Md.Code(c.Source.ToString()) },
                new[] { "Group", c.Group },
                new[] { "Local name", c.LocalName },
                new[] { "Flags", c.Flags },
                new[] { "Manual test", $"{ix.TestId[c]} in [tests]({Md.Rel(doc, ManualTestWriter.CommandTestDoc(project))})" },
                new[] { "Source map id", Md.Code(ModelIndex.CommandId(c)) },
            }.Where(r => !string.IsNullOrEmpty(r[1]))));
            sb.Append("\n**How to start it:** ").Append(string.Join("; ", ix.ReachCommand(c))).Append("\n\n");

            var ui = c.Flow.Where(s => s.Kind != FlowKind.Call).ToList();
            if (c.Flow.Count == 0)
            {
                sb.Append(c.Extra.ContainsKey("methodNotFound")
                    ? "The method's body is not in the scanned folder (another assembly or project), so its flow is unknown.\n\n"
                    : "No UI steps found in the method body.\n\n");
                continue;
            }
            sb.Append("**Flow** (indent = call depth):\n\n");
            foreach (var s in c.Flow) sb.Append(new string(' ', 2 * s.Depth)).Append("- ").Append(StepLine(doc, s)).Append('\n');
            sb.Append('\n');
            if (ui.Count > 0) sb.Append(Mermaid(c, ui)).Append('\n');
        }
        sink.Write(doc, sb.ToString());
    }

    private string StepLine(string doc, FlowStep s)
    {
        var text = s.Kind switch
        {
            FlowKind.Call => $"calls {Md.Code(s.Target ?? s.Text)}",
            FlowKind.Dialog or FlowKind.Palette when s.UiFormId != null && ix.FormsById.TryGetValue(s.UiFormId, out var f)
                => $"**{s.Kind}** [{Md.Cell(f.Title)}]({Md.Rel(doc, ix.FormDoc[f])}) ({Md.Code(s.Target)})",
            FlowKind.Dialog or FlowKind.Palette => $"**{s.Kind}** {Md.Code(s.Target ?? s.Text)}",
            FlowKind.SendCommand => $"**SendCommand** {Md.Code(s.Target ?? s.Text)}",
            _ => $"**{s.Kind}** \"{Md.Cell(s.Text)}\"",
        };
        var extra = s.Extra.Count > 0 ? " (" + string.Join(", ", s.Extra.Select(kv => $"{kv.Key}: {Md.Cell(kv.Value)}")) + ")" : "";
        return $"{text}{extra} {(s.Source != null ? Md.Code(s.Source.ToString()) : "")}".TrimEnd();
    }

    private string Mermaid(CommandEntry c, List<FlowStep> ui)
    {
        var sb = new StringBuilder("```mermaid\nflowchart TD\n");
        sb.Append($"  start([{Md.Mermaid(c.Name)}])\n");
        string prev = "start";
        int i = 0;
        foreach (var s in ui.Take(40))
        {
            var id = $"s{++i}";
            var label = s.Kind switch
            {
                FlowKind.Dialog or FlowKind.Palette => $"{s.Kind}: {(s.UiFormId != null ? ix.FormsById[s.UiFormId].Title : s.Target)}",
                FlowKind.SendCommand => $"Command: {s.Target ?? s.Text}",
                _ => $"{s.Kind}: {Trunc(s.Text, 50)}",
            };
            var shape = s.Kind switch
            {
                FlowKind.Prompt or FlowKind.Selection => $"[/{Md.Mermaid(label)}/]",
                FlowKind.Dialog or FlowKind.Palette => $"[[{Md.Mermaid(label)}]]",
                _ => $"[{Md.Mermaid(label)}]",
            };
            sb.Append($"  {id}{shape}\n  {prev} --> {id}\n");
            prev = id;
        }
        if (ui.Count > 40) sb.Append($"  more[\"... {ui.Count - 40} more steps\"]\n  {prev} --> more\n");
        return sb.Append("```\n").ToString();
    }

    // ------------------------------------------------------------ ui

    private void WriteUiIndex()
    {
        const string doc = DocsLayout.RefDialogs + "/index.md";
        var sb = new StringBuilder("# Dialogs, windows and palettes\n\n");
        foreach (var g in M.Forms.GroupBy(f => f.Kind).OrderBy(g => g.Key))
        {
            sb.Append($"## {g.Key} ({g.Count()})\n\n");
            sb.Append(Md.Table(new[] { "Title", "Project", "Class / resource", "Controls", "Opened by", "Source" },
                g.OrderBy(f => f.Project).ThenBy(f => f.Title).Select(f => new[]
                {
                    $"[{Md.Cell(f.Title)}]({Md.Rel(doc, ix.FormDoc[f])})", f.Project,
                    Md.Code(f.ClassNames.FirstOrDefault() ?? f.ResourceId), CountControls(f.Controls).ToString(),
                    string.Join(", ", ix.OpenersByForm[f.Id].Select(o => o.Command).Distinct().Take(4)
                        .Select(c => $"[{Md.Cell(c.Name)}]({ix.CommandLink(doc, c)})")),
                    Md.Code(f.Source.ToString()),
                })));
            sb.Append('\n');
        }
        sink.Write(doc, sb.ToString());
    }

    private static int CountControls(List<UiControl> cs) => cs.Sum(c => 1 + CountControls(c.Children));

    private void WriteForm(UiForm f)
    {
        var doc = ix.FormDoc[f];
        var sb = new StringBuilder($"# {f.Kind}: {f.Title}\n\n");
        sb.Append($"![{f.Title} wireframe]({Md.Rel(doc, ix.FormAsset[f])})\n\n");
        sb.Append(Md.Table(new[] { "Field", "Value" }, new List<string?[]>
        {
            new[] { "Id", Md.Code(f.Id) },
            new[] { "Project", f.Project },
            new[] { "Source", Md.Code(f.Source.ToString()) },
            new[] { "Classes", string.Join(", ", f.ClassNames.Select(Md.Code)) },
            new[] { "Resource", Md.Code(f.ResourceId) },
            new[] { "Size", f.Width != null ? $"{f.Width} × {f.Height} {f.Units}" : f.Units },
            new[] { "Source map id", Md.Code(ModelIndex.FormId(f)) },
        }.Concat(f.Extra.Select(kv => new[] { kv.Key, Md.Cell(kv.Value) })).Where(r => !string.IsNullOrEmpty(r[1]))));

        var openers = ix.OpenersByForm[f.Id].ToList();
        sb.Append("\n## Opened by\n\n");
        if (openers.Count == 0) sb.Append("No scanned command reaches this window.\n");
        foreach (var o in openers.DistinctBy(o => o.Command))
            sb.Append($"- [{Md.Cell(o.Command.Name)}]({ix.CommandLink(doc, o.Command)}) at {Md.Code(o.Step.Source?.ToString())}\n");
        sb.Append("\n**How to reach it:** ").Append(string.Join(" → ", ix.ReachForm(f))).Append("\n\n");

        sb.Append("## Controls\n\n");
        var rows = new List<string?[]>();
        void Add(List<UiControl> cs, int depth)
        {
            foreach (var c in cs)
            {
                rows.Add(new[]
                {
                    new string('·', depth) + (depth > 0 ? " " : "") + Md.Cell(c.Name), c.Type, Md.Cell(c.Text),
                    c.X != null ? $"{c.X},{c.Y} {c.W}×{c.H}" : "", string.Join("; ", c.Events),
                    Md.Code(c.Source?.ToString()),
                });
                Add(c.Children, depth + 1);
            }
        }
        Add(f.Controls, 0);
        sb.Append(rows.Count == 0 ? "None found.\n" : Md.Table(new[] { "Name", "Type", "Text", "Bounds", "Events", "Source" }, rows));
        sink.Write(doc, sb.ToString());
    }

    internal static string? Trunc(string? s, int n) => s == null ? null : s.Length <= n ? s : s[..(n - 1)] + "…";
}
